#!/bin/sh
# Generates salty_info.h: every piece of information shown by the Salty
# settings app that comes from the repository (Makefile variables, git, themes
# folder) instead of being hardcoded in the C++ sources.
#
# usage: generate_info.sh <output.h> <os_version> <kernel_version> \
#          <epsilon_source_version> <commit> <platform> <palette.txt> \
#          <generate_theme.py>
set -eu

out="$1"
os_version="$2"
kernel_version="$3"
epsilon_source_version="$4"
commit="$5"
platform="$6"
palette_file="$7"
theme_generator="$8"

# Keeps a value usable inside a C string literal
clean() {
  printf '%s' "$1" | tr -d '"\\\n\r'
}

[ -n "$os_version" ] || os_version="dev"
[ -n "$commit" ] || commit="?"

tmp="$out.tmp"
mkdir -p "$(dirname "$out")"

{
  echo "// Generated by generate_info.sh, do not edit."
  echo "#pragma once"
  echo
  echo "#define SALTY_INFO_OS_VERSION \"$(clean "$os_version")\""
  echo "#define SALTY_INFO_KERNEL_VERSION \"$(clean "$kernel_version")\""
  echo "#define SALTY_INFO_EPSILON_SOURCE_VERSION \"$(clean "$epsilon_source_version")\""
  echo "#define SALTY_INFO_COMMIT \"$(clean "$commit")\""
  echo "#define SALTY_INFO_PLATFORM \"$(clean "$platform")\""
  echo
  echo "namespace SaltyInfo {"
  echo
  echo "// Slot order of a theme palette (first column of themes/epsilon/palette.txt)"
  echo "constexpr const char* k_paletteSlotNames[] = {"
  awk '!/^[[:space:]]*(#|$)/ { printf "    \"%s\",\n", $1 }' "$palette_file"
  echo "};"
  echo "constexpr int k_numberOfPaletteSlotNames ="
  echo "    sizeof(k_paletteSlotNames) / sizeof(k_paletteSlotNames[0]);"
  echo
  echo "// Icon order of a theme (FIXED_ICON_FILES of themes/generate_theme.py)"
  echo "constexpr const char* k_iconNames[] = {"
  awk '
    /^FIXED_ICON_FILES[[:space:]]*=/ { inlist = 1; next }
    inlist && /^\]/ { inlist = 0 }
    inlist {
      if (match($0, /"[^"]+"/)) {
        name = substr($0, RSTART + 1, RLENGTH - 2)
        sub(/_icon\.png$/, "", name)
        printf "    \"%s%s\",\n", toupper(substr(name, 1, 1)), substr(name, 2)
      }
    }' "$theme_generator"
  echo "};"
  echo "constexpr int k_numberOfIconNames ="
  echo "    sizeof(k_iconNames) / sizeof(k_iconNames[0]);"
  echo
  echo "}  // namespace SaltyInfo"
} > "$tmp"

# Only touch the header when something changed, to avoid useless rebuilds
if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
  rm -f "$tmp"
else
  mv "$tmp" "$out"
fi
